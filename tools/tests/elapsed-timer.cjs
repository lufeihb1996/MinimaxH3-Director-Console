const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('frontend/app.js', 'utf8');
const fixture = { id: 1, status: 'RUNNING', generation_started_at: 100, generation_finished_at: 0, generation_elapsed_seconds: 0 };
const cells = [{ dataset: { shotElapsed: '1' }, textContent: '—' }];
let now = 162000;
const sandbox = { $: () => null, state: { shots: [fixture] }, document: { querySelectorAll: selector => selector === '[data-shot-elapsed]' ? cells : [] }, Date: { now: () => now } };
vm.createContext(sandbox);
vm.runInContext(source.slice(source.indexOf('function formatElapsedSeconds('), source.indexOf('function videoProgressDetail(')), sandbox);
assert.equal(sandbox.shotElapsedText(fixture, 100), '0秒');
assert.equal(sandbox.shotElapsedText(fixture, 162), '1分2秒');
assert.equal(sandbox.shotElapsedText(fixture, 3761), '1时1分1秒');
assert.equal(sandbox.shotElapsedText(fixture, 99), '0秒');
assert.equal(sandbox.shotElapsedText({ ...fixture, status: 'QUEUED', generation_finished_at: 120 }), '—');
assert.equal(sandbox.shotElapsedText({ ...fixture, status: 'RUNNING', generation_started_at: 0 }), '—');
sandbox.refreshShotElapsed();
assert.equal(cells[0].textContent, '1分2秒');
now = 165000;
sandbox.refreshShotElapsed();
assert.equal(cells[0].textContent, '1分5秒');
fixture.status = 'DONE';
fixture.generation_finished_at = 170;
fixture.generation_elapsed_seconds = 70;
now = 900000;
sandbox.refreshShotElapsed();
assert.equal(cells[0].textContent, '1分10秒');
assert.equal(sandbox.shotElapsedText({ ...fixture, status: 'FAILED' }, 1000), '1分10秒');
fixture.status = 'PREPARING';
fixture.generation_started_at = 900;
fixture.generation_finished_at = 0;
fixture.generation_elapsed_seconds = 0;
assert.equal(sandbox.shotElapsedText(fixture, 901), '1秒');
console.log('PASS: live ticking, refresh from persisted start, final duration frozen, queued state and regeneration reset.');

assert.equal(sandbox.songElapsedText({song_status:'RUNNING',song_started_at:100},162),'1分2秒');
assert.equal(sandbox.songElapsedText({song_status:'RUNNING',song_started_at:0},162),'—');
assert.equal(sandbox.songElapsedText({song_status:'FAILED',song_started_at:100,song_finished_at:170,song_elapsed_seconds:70},999),'1分10秒');
